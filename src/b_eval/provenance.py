"""Build a deterministic baseline/candidate freeze manifest.

The manifest deliberately contains no timestamp or other run-specific value.  A
fixed source/configuration/environment snapshot therefore has one canonical
SHA-256 and can be regenerated byte-for-byte for audit and delivery checks.

Run from the repository root with::

    python -m src.b_eval.provenance \
        --out results/extreme_speed/baseline_manifest.json
"""
from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass, fields, is_dataclass
import hashlib
import json
import math
import os
from pathlib import Path
import platform
from types import MappingProxyType
from typing import Any, Mapping
import subprocess
import sys

from ..pack_dist_windows import RUNTIME_MODULES


ROOT = Path(__file__).resolve().parents[2]
PHYSICS_RULES_VERSION = "cumcm-b-offline-physics-v1"
GATE_VERSION = "q3-q4-extreme-speed-gates-v1"
MANIFEST_SCHEMA_VERSION = 1

PROBLEM_STRATA = {
    "q3": ("d0",),
    "q4": ("d5", "d10", "d16"),
}
EXECUTION_BOUND_FIELDS = (
    "loop_iterations_max",
    "recursion_depth_max",
    "candidates_per_expansion_max",
    "candidate_expansions_total_max",
)
DEFAULT_EXECUTION_BOUNDS = {
    "loop_iterations_max": 100_000,
    "recursion_depth_max": 64,
    "candidates_per_expansion_max": 50_000,
    "candidate_expansions_total_max": 5_000_000,
}


def _canonical_json(value: Mapping[str, Any]) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")


def source_digest(files: Mapping[str, bytes]) -> str:
    """Hash path/content pairs after normalizing text line endings."""
    digest = hashlib.sha256()
    for name, content in sorted(files.items()):
        digest.update(name.encode("utf-8") + b"\0")
        digest.update(content.replace(b"\r\n", b"\n") + b"\0")
    return digest.hexdigest()


def manifest_digest(payload: Mapping[str, Any]) -> str:
    """Return the canonical digest, excluding the self-referential digest field."""
    material = dict(payload)
    material.pop("manifest_sha256", None)
    return hashlib.sha256(_canonical_json(material)).hexdigest()


def verify_manifest_digest(manifest: Mapping[str, Any]) -> bool:
    recorded = manifest.get("manifest_sha256")
    return isinstance(recorded, str) and recorded == manifest_digest(manifest)


def _runtime_paths() -> tuple[str, ...]:
    return tuple(f"src/b_sim/{name}" for name in RUNTIME_MODULES)


def runtime_source_files_from_worktree(root: Path = ROOT) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    for relative in _runtime_paths():
        path = root / relative
        if not path.is_file():
            raise ValueError(f"Runtime source file is missing: {relative}")
        files[relative] = path.read_bytes()
    return files


def _git(root: Path, *args: str) -> bytes:
    return subprocess.check_output(["git", "-C", str(root), *args])


def resolve_commit(reference: str, root: Path = ROOT) -> str:
    return _git(root, "rev-parse", "--verify", reference + "^{commit}").decode().strip()


def runtime_source_files_from_git(reference: str, root: Path = ROOT) -> dict[str, bytes]:
    commit = resolve_commit(reference, root)
    files: dict[str, bytes] = {}
    for relative in _runtime_paths():
        try:
            files[relative] = _git(root, "show", f"{commit}:{relative}")
        except subprocess.CalledProcessError as exc:
            raise ValueError(
                f"Baseline {commit} does not contain required runtime source {relative}"
            ) from exc
    return files


def _cpu_model() -> str:
    model = platform.processor().strip()
    if model:
        return model
    if sys.platform.startswith("linux"):
        try:
            for line in Path("/proc/cpuinfo").read_text(encoding="utf-8").splitlines():
                if line.lower().startswith("model name"):
                    return line.split(":", 1)[1].strip()
        except OSError:
            pass
    return os.environ.get("PROCESSOR_IDENTIFIER", "").strip() or platform.machine() or "unknown"


def environment_snapshot(worker_threads: int) -> dict[str, Any]:
    if isinstance(worker_threads, bool) or not isinstance(worker_threads, int) or worker_threads <= 0:
        raise ValueError("worker_threads must be a positive integer")
    return {
        "python": {
            "implementation": platform.python_implementation(),
            "version": platform.python_version(),
        },
        "os": {
            "system": platform.system(),
            "release": platform.release(),
            "version": platform.version(),
            "machine": platform.machine(),
        },
        "cpu": {
            "model": _cpu_model(),
            "logical_count": os.cpu_count(),
        },
        "worker_threads": worker_threads,
    }


def validate_execution_bounds(bounds: Mapping[str, Any]) -> dict[str, int]:
    if not isinstance(bounds, Mapping):
        raise ValueError("execution bounds must be an object")
    expected = set(EXECUTION_BOUND_FIELDS)
    unknown = set(bounds) - expected
    missing = expected - set(bounds)
    if unknown:
        raise ValueError(f"Unknown execution bound fields: {sorted(unknown)}")
    if missing:
        raise ValueError(f"Missing execution bound fields: {sorted(missing)}")
    validated: dict[str, int] = {}
    for name in EXECUTION_BOUND_FIELDS:
        value = bounds[name]
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            raise ValueError(f"Execution bound {name} must be a positive integer")
        validated[name] = value
    if validated["candidate_expansions_total_max"] < validated["candidates_per_expansion_max"]:
        raise ValueError(
            "candidate_expansions_total_max conflicts with candidates_per_expansion_max"
        )
    return validated


def _validate_finite_json(value: Any, path: str) -> None:
    if value is None or isinstance(value, (bool, int, str)):
        return
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f"Non-finite configuration value at {path}")
        return
    if isinstance(value, Mapping):
        for key, item in value.items():
            if not isinstance(key, str):
                raise ValueError(f"Non-string configuration key at {path}")
            _validate_finite_json(item, f"{path}.{key}")
        return
    if isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            _validate_finite_json(item, f"{path}[{index}]")
        return
    raise ValueError(f"Configuration value at {path} is not JSON-compatible")


def _normalized_override(name: str, value: Any, default: Any) -> Any:
    if isinstance(default, bool):
        if not isinstance(value, bool):
            raise ValueError(f"StrategyConfig field {name} must be bool")
        return value
    if isinstance(default, int):
        if isinstance(value, bool) or not isinstance(value, int):
            raise ValueError(f"StrategyConfig field {name} must be int")
        return value
    if isinstance(default, float):
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValueError(f"StrategyConfig field {name} must be numeric")
        converted = float(value)
        if not math.isfinite(converted):
            raise ValueError(f"Non-finite configuration value at {name}")
        return converted
    if not isinstance(value, type(default)):
        raise ValueError(f"StrategyConfig field {name} has an invalid type")
    return value


def _complete_config(config_class: type, problem: str, overrides: Mapping[str, Any]) -> dict[str, Any]:
    if not is_dataclass(config_class):
        raise TypeError("config_class must be a dataclass type")
    if not isinstance(overrides, Mapping):
        raise ValueError(f"{problem} configuration overrides must be an object")
    directional = problem == "q4"
    instance = config_class(directional_probe=directional)
    complete = asdict(instance)
    known = {field.name for field in fields(config_class)}
    unknown = set(overrides) - known
    if unknown:
        raise ValueError(f"Unknown StrategyConfig fields for {problem}: {sorted(unknown)}")
    if "directional_probe" in overrides and overrides["directional_probe"] is not directional:
        raise ValueError(f"directional_probe conflicts with {problem} mode")
    for name, value in overrides.items():
        complete[name] = _normalized_override(name, value, complete[name])
    _validate_finite_json(complete, f"configurations.{problem}")
    return complete


def freeze_problem_configurations(
    baseline_config_class: type,
    candidate_config_class: type,
    *,
    candidate_overrides: Mapping[str, Mapping[str, Any]] | None = None,
    execution_bounds: Mapping[str, Mapping[str, Any]] | None = None,
) -> dict[str, Any]:
    """Resolve complete Q3/Q4 configs under an exact, fail-closed schema."""
    candidate_overrides = candidate_overrides or {}
    if not isinstance(candidate_overrides, Mapping):
        raise ValueError("candidate_overrides must be an object")
    unknown_problems = set(candidate_overrides) - set(PROBLEM_STRATA)
    if unknown_problems:
        raise ValueError(f"Unknown problem configuration fields: {sorted(unknown_problems)}")

    if execution_bounds is None:
        execution_bounds = {
            problem: dict(DEFAULT_EXECUTION_BOUNDS) for problem in PROBLEM_STRATA
        }
    if not isinstance(execution_bounds, Mapping):
        raise ValueError("execution_bounds must be an object")
    unknown_bound_groups = set(execution_bounds) - set(PROBLEM_STRATA)
    missing_bound_groups = set(PROBLEM_STRATA) - set(execution_bounds)
    if unknown_bound_groups:
        raise ValueError(f"Unknown execution-bound problem fields: {sorted(unknown_bound_groups)}")
    if missing_bound_groups:
        raise ValueError(f"Missing execution-bound problem fields: {sorted(missing_bound_groups)}")

    result: dict[str, Any] = {}
    for problem, strata in PROBLEM_STRATA.items():
        bounds = validate_execution_bounds(execution_bounds[problem])
        result[problem] = {
            "strata": list(strata),
            "baseline": {
                "strategy_config": _complete_config(baseline_config_class, problem, {}),
                "execution_bounds": dict(bounds),
            },
            "candidate": {
                "strategy_config": _complete_config(
                    candidate_config_class, problem, candidate_overrides.get(problem, {})
                ),
                "execution_bounds": dict(bounds),
            },
        }
    return result


def _freeze(value: Any) -> Any:
    if isinstance(value, dict):
        return MappingProxyType({key: _freeze(item) for key, item in value.items()})
    if isinstance(value, list):
        return tuple(_freeze(item) for item in value)
    if isinstance(value, tuple):
        return tuple(_freeze(item) for item in value)
    return value


def _thaw(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {key: _thaw(item) for key, item in value.items()}
    if isinstance(value, tuple):
        return [_thaw(item) for item in value]
    return value


@dataclass(frozen=True)
class FrozenManifest:
    """Recursively immutable manifest with a verified canonical digest."""

    data: Mapping[str, Any]

    @property
    def sha256(self) -> str:
        return str(self.data["manifest_sha256"])

    def to_dict(self) -> dict[str, Any]:
        return _thaw(self.data)


def build_manifest(
    *,
    baseline_commit: str,
    candidate_commit: str,
    baseline_runtime_files: Mapping[str, bytes],
    candidate_runtime_files: Mapping[str, bytes],
    baseline_config_class: type,
    candidate_config_class: type,
    worker_threads: int,
    candidate_overrides: Mapping[str, Mapping[str, Any]] | None = None,
    execution_bounds: Mapping[str, Mapping[str, Any]] | None = None,
    environment: Mapping[str, Any] | None = None,
) -> FrozenManifest:
    if not baseline_commit or not candidate_commit:
        raise ValueError("baseline and candidate commit identifiers are required")
    if isinstance(worker_threads, bool) or not isinstance(worker_threads, int) or worker_threads <= 0:
        raise ValueError("worker_threads must be a positive integer")
    runtime_paths = list(_runtime_paths())
    if set(baseline_runtime_files) != set(runtime_paths):
        raise ValueError("baseline runtime source set does not match the delivery closure")
    if set(candidate_runtime_files) != set(runtime_paths):
        raise ValueError("candidate runtime source set does not match the delivery closure")
    snapshot = dict(environment) if environment is not None else environment_snapshot(worker_threads)
    if snapshot.get("worker_threads") != worker_threads:
        raise ValueError("environment worker_threads conflicts with the frozen worker count")
    _validate_finite_json(snapshot, "provenance.environment")

    payload: dict[str, Any] = {
        "schema_version": MANIFEST_SCHEMA_VERSION,
        "artifact": "q3-q4-extreme-speed-baseline-manifest",
        "provenance": {
            "baseline": {
                "commit": baseline_commit,
                "runtime_source_sha256": source_digest(baseline_runtime_files),
            },
            "candidate": {
                "commit": candidate_commit,
                "runtime_source_sha256": source_digest(candidate_runtime_files),
            },
            "runtime_files": runtime_paths,
            "physics_rules_version": PHYSICS_RULES_VERSION,
            "gate_version": GATE_VERSION,
            "environment": snapshot,
        },
        "configurations": freeze_problem_configurations(
            baseline_config_class,
            candidate_config_class,
            candidate_overrides=candidate_overrides,
            execution_bounds=execution_bounds,
        ),
    }
    payload["manifest_sha256"] = manifest_digest(payload)
    return FrozenManifest(_freeze(payload))


def write_manifest(path: Path, manifest: FrozenManifest | Mapping[str, Any]) -> None:
    data = manifest.to_dict() if isinstance(manifest, FrozenManifest) else dict(manifest)
    if not verify_manifest_digest(data):
        raise ValueError("Refusing to write a manifest with an invalid digest")
    encoded = json.dumps(
        data,
        ensure_ascii=False,
        sort_keys=True,
        indent=2,
        allow_nan=False,
    ) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(encoded, encoding="utf-8", newline="\n")
    temporary.replace(path)


def generate_baseline_manifest(
    *,
    baseline_ref: str = "HEAD",
    worker_threads: int = 4,
    candidate_overrides: Mapping[str, Mapping[str, Any]] | None = None,
    execution_bounds: Mapping[str, Mapping[str, Any]] | None = None,
) -> FrozenManifest:
    """Snapshot source and config classes, rejecting concurrent source drift."""
    # Lazy import avoids making the existing benchmark depend on this CLI.
    from ..b_optimization_benchmark import frozen_versions

    baseline_commit = resolve_commit(baseline_ref)
    candidate_commit = resolve_commit("HEAD")
    baseline_files = runtime_source_files_from_git(baseline_commit)
    candidate_files_before = runtime_source_files_from_worktree()
    with frozen_versions(baseline_commit) as (bundles, _metadata):
        candidate_files_after = runtime_source_files_from_worktree()
        if source_digest(candidate_files_before) != source_digest(candidate_files_after):
            raise RuntimeError("Runtime source changed while the freeze manifest was generated")
        return build_manifest(
            baseline_commit=baseline_commit,
            candidate_commit=candidate_commit,
            baseline_runtime_files=baseline_files,
            candidate_runtime_files=candidate_files_before,
            baseline_config_class=bundles["baseline"]["strategy"].StrategyConfig,
            candidate_config_class=bundles["candidate"]["strategy"].StrategyConfig,
            worker_threads=worker_threads,
            candidate_overrides=candidate_overrides,
            execution_bounds=execution_bounds,
        )


def _load_json_object(raw: str, argument: str) -> Mapping[str, Any]:
    text = raw if raw.lstrip().startswith("{") else Path(raw).read_text(encoding="utf-8-sig")
    value = json.loads(text)
    if not isinstance(value, dict):
        raise ValueError(f"{argument} must contain a JSON object")
    return value


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=ROOT / "results/extreme_speed/baseline_manifest.json",
    )
    parser.add_argument("--baseline-ref", default="HEAD")
    parser.add_argument("--worker-threads", type=int, default=4)
    parser.add_argument(
        "--candidate-config",
        help="JSON object or path with optional q3/q4 StrategyConfig overrides",
    )
    parser.add_argument(
        "--execution-bounds",
        help="JSON object or path with complete q3/q4 execution bounds",
    )
    args = parser.parse_args(argv)
    try:
        overrides = (
            _load_json_object(args.candidate_config, "--candidate-config")
            if args.candidate_config
            else None
        )
        bounds = (
            _load_json_object(args.execution_bounds, "--execution-bounds")
            if args.execution_bounds
            else None
        )
        manifest = generate_baseline_manifest(
            baseline_ref=args.baseline_ref,
            worker_threads=args.worker_threads,
            candidate_overrides=overrides,
            execution_bounds=bounds,
        )
        write_manifest(args.out, manifest)
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as exc:
        parser.error(str(exc))
    print(
        json.dumps(
            {"path": str(args.out), "manifest_sha256": manifest.sha256},
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
